import AppKit

/// Watches this Mac's clipboard and applies clipboard contents from the other side.
/// Text and images only. Items that password managers mark as concealed or transient are never sent.
public final class ClipboardSync {
    public static let maxTextBytes = 2_000_000
    public static let maxImageBytes = 6_000_000

    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Main thread. Called when something new is copied on this Mac.
    public var onLocalCopy: ((ClipboardMsg) -> Void)?

    public init() {}

    /// Starts watching. What's already on the clipboard isn't sent, only new copies.
    public func start() {
        DispatchQueue.main.async {
            self.lastChangeCount = NSPasteboard.general.changeCount
            self.timer?.invalidate()
            self.timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in self?.check() }
        }
    }

    public func stop() {
        DispatchQueue.main.async {
            self.timer?.invalidate()
            self.timer = nil
        }
    }

    /// Puts the other side's copy on this Mac's clipboard.
    public func apply(_ message: ClipboardMsg) {
        DispatchQueue.main.async {
            let pb = NSPasteboard.general
            pb.clearContents()
            if let text = message.text {
                pb.setString(text, forType: .string)
            } else if let png = message.png {
                pb.setData(png, forType: .png)
                if let image = NSImage(data: png), let tiff = image.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
            // Don't send our own write straight back.
            self.lastChangeCount = pb.changeCount
            Log.info("clipboard: received \(ClipboardSync.describe(message)) from the other Mac")
        }
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        let types = Set(pb.types ?? [])
        if !types.isDisjoint(with: ClipboardSync.privateTypes) {
            Log.info("clipboard: skipped a private copy (password manager)")
            return
        }
        var message: ClipboardMsg?
        if let text = pb.string(forType: .string) {
            if text.utf8.count <= ClipboardSync.maxTextBytes {
                message = ClipboardMsg(text: text, png: nil)
            } else {
                Log.info("clipboard: text too large to send (\(text.utf8.count / 1000) KB)")
            }
        } else if let png = ClipboardSync.pngData(pb) {
            if png.count <= ClipboardSync.maxImageBytes {
                message = ClipboardMsg(text: nil, png: png)
            } else {
                Log.info("clipboard: image too large to send (\(png.count / 1000) KB)")
            }
        }
        guard let message else { return }
        Log.info("clipboard: sending \(ClipboardSync.describe(message))")
        onLocalCopy?(message)
    }

    private static func pngData(_ pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    /// For logs: size and kind only, never the contents.
    static func describe(_ m: ClipboardMsg) -> String {
        if let t = m.text { return "text (\(t.count) characters)" }
        if let p = m.png { return "image (\(p.count / 1000) KB)" }
        return "nothing"
    }
}
